CHAR_ROLE = {
    ".": "empty",
    "O": "outline",
    "B": "base",
    "L": "light",
    "S": "pattern",
    "A": "detail",
    "E": "eye",
    "W": "light",
    "P": "detail",
    "Z": "zzz",
}


def parse_art(rows, palette):
    """Convert a list of 32 strings (32 chars wide) into a tagged-RGBA grid."""
    assert len(rows) == SIZE, f"expected {SIZE} rows, got {len(rows)}"
    grid = empty_grid()
    for y, row in enumerate(rows):
        assert len(row) == SIZE, f"row {y} has len {len(row)} != {SIZE}: {row!r}"
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            grid[y][x] = (palette[ch], CHAR_ROLE[ch])
    return grid


def stamp(base_rows, patch_rows, ox=0, oy=0):
    """Overlay non-'.' pixels from patch_rows onto a copy of base_rows."""
    out = [list(r) for r in base_rows]
    for dy, row in enumerate(patch_rows):
        y = oy + dy
        if not (0 <= y < SIZE):
            continue
        for dx, ch in enumerate(row):
            x = ox + dx
            if 0 <= x < SIZE and ch != ".":
                out[y][x] = ch
    return ["".join(r) for r in out]


def _rows(block):
    """Convert a multiline 32-col template to 32 rows."""
    lines = [ln for ln in block.splitlines() if ln.strip("\n") != ""]
    assert len(lines) == SIZE, f"expected 32 lines, got {len(lines)}"
    return [ln.ljust(SIZE, ".")[:SIZE] for ln in lines]


