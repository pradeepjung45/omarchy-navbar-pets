"""Colorful 32x32 pixel-art animal sprite generator.

Produces 32-frame RGBA spritesheets (matching Frames.js's 32-frame layout) for:
  - Colorful cats (cat-ginger, cat-calico, cat-tuxedo) derived from oneko's
    hand-drawn neko/tora bitmaps
  - Colorful dogs (dog-golden from oneko's dog, plus custom dog-husky & dog-corgi)
  - Rats (rat-gray, rat-white)
  - Pandas (panda, panda-red)
  - Horses (horse-brown, horse-white)

All output uses semantic pixel tags alongside RGBA colors so the 32->16
downscaler preserves 1px outlines, eyes, noses, and vibrant markings cleanly.
"""

from pathlib import Path
import re

SIZE = 32

# Semantic roles in priority order for 2x2 -> 1px downscaling
ROLE_PRIORITY = {
    "eye": 6,
    "detail": 5,
    "zzz": 5,
    "pattern": 4,
    "light": 3,
    "base": 2,
    "outline": 1,
    "empty": 0,
}


def read_xbm(path):
    """Parse an XBM bitmap into a 32x32 list of 0/1."""
    text = Path(path).read_text()
    width = int(re.search(r"_width (\d+)", text).group(1))
    height = int(re.search(r"_height (\d+)", text).group(1))
    data = [int(b, 16) for b in re.findall(r"0x([0-9a-fA-F]{2})", text)]
    stride = (width + 7) // 8
    return [
        [(data[y * stride + (x >> 3)] >> (x & 7)) & 1 for x in range(width)]
        for y in range(height)
    ]


def flip_grid(grid):
    """Horizontally mirror a 32x32 tagged-RGBA grid."""
    return [list(reversed(row)) for row in grid]


def empty_grid():
    return [[((0, 0, 0, 0), "empty") for _ in range(SIZE)] for _ in range(SIZE)]


def is_border_ink(mask, ink, x, y):
    """True if an ink pixel sits on the outer boundary of the silhouette."""
    if not ink[y][x]:
        return False
    for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1)):
        ny, nx = y + dy, x + dx
        if ny < 0 or ny >= SIZE or nx < 0 or nx >= SIZE or not mask[ny][nx]:
            return True
    return False


def _zzz_region(frame_name, x, y):
    if frame_name == "sleep1":
        return y <= 11 and x <= 23
    if frame_name == "sleep2":
        return (y <= 14 and x <= 23) or (y <= 13 and x <= 25)
    return False


def _calico_patch(x, y):
    """Return organic circular calico patch ('orange', 'dark', or None)."""
    # Left ear / temple orange patch, right ear dark patch, back/rump patches
    spots_orange = ((10, 6, 4.2), (8, 22, 4.8), (22, 16, 4.5), (5, 13, 3.8))
    spots_dark = ((21, 7, 4.2), (24, 24, 4.5), (12, 19, 3.6), (27, 13, 3.5))
    for cx, cy, r in spots_orange:
        if (x - cx) ** 2 + (y - cy) ** 2 <= r * r:
            return "orange"
    for cx, cy, r in spots_dark:
        if (x - cx) ** 2 + (y - cy) ** 2 <= r * r:
            return "dark"
    return None


def build_xbm_cat(vendor_dir, frame_name, variant):
    """Colorize oneko's neko (+ tora stripes) XBM into a 32x32 tagged-RGBA grid."""
    neko_img = read_xbm(vendor_dir / "bitmaps" / "neko" / f"{frame_name}.xbm")
    tora_img = read_xbm(vendor_dir / "bitmaps" / "tora" / f"{frame_name}_tora.xbm")
    mask = read_xbm(vendor_dir / "bitmasks" / "neko" / f"{frame_name}_mask.xbm")

    palettes = {
        "cat-ginger": {
            "outline": (86, 40, 18, 255),
            "base": (244, 146, 56, 255),
            "light": (255, 226, 182, 255),
            "stripe": (196, 82, 24, 255),
            "eye": (54, 174, 88, 255),
            "pink": (246, 148, 166, 255),
            "zzz": (122, 198, 255, 255),
        },
        "cat-calico": {
            "outline": (62, 46, 50, 255),
            "base": (250, 245, 236, 255),
            "patch1": (240, 128, 46, 255),
            "patch2": (78, 62, 64, 255),
            "eye": (218, 152, 38, 255),
            "pink": (246, 148, 166, 255),
            "zzz": (122, 198, 255, 255),
        },
        "cat-tuxedo": {
            "outline": (20, 22, 30, 255),
            "base": (50, 55, 68, 255),
            "light": (246, 248, 252, 255),
            "detail": (124, 132, 154, 255),
            "eye": (236, 200, 58, 255),
            "pink": (246, 148, 166, 255),
            "zzz": (122, 198, 255, 255),
        },
    }
    pal = palettes[variant]
    grid = empty_grid()

    front_frames = {"mati2", "jare2", "mati3", "awake", "down1", "down2"}
    for y in range(SIZE):
        for x in range(SIZE):
            if not mask[y][x]:
                continue
            ink = bool(neko_img[y][x])
            stripe = bool(tora_img[y][x]) and not ink

            if _zzz_region(frame_name, x, y):
                if ink:
                    grid[y][x] = (pal["zzz"], "zzz")
                continue

            if ink:
                if frame_name in front_frames and y in (10, 11, 12) and x in (13, 19):
                    grid[y][x] = (pal["eye"], "eye")
                elif frame_name in front_frames and y == 14 and x == 16:
                    grid[y][x] = (pal["pink"], "detail")
                elif variant == "cat-tuxedo" and not is_border_ink(mask, neko_img, x, y):
                    if y >= 15 and x in range(13, 20):
                        grid[y][x] = (pal["outline"], "outline")
                    else:
                        grid[y][x] = (pal["detail"], "detail")
                else:
                    grid[y][x] = (pal["outline"], "outline")
                continue

            if variant == "cat-ginger":
                if (frame_name in front_frames and y in range(13, 17) and x in range(13, 20)) or (
                    frame_name in front_frames and y in range(19, 27) and x in range(14, 19)
                ) or (y >= 26):
                    grid[y][x] = (pal["light"], "light")
                elif stripe:
                    grid[y][x] = (pal["stripe"], "pattern")
                else:
                    grid[y][x] = (pal["base"], "base")

            elif variant == "cat-calico":
                # Keep muzzle & paws mostly cream-white, patches on head/ears/body
                is_muzzle = frame_name in front_frames and y in range(13, 17) and x in range(13, 20)
                if is_muzzle:
                    grid[y][x] = (pal["base"], "light")
                else:
                    patch = _calico_patch(x, y)
                    if patch == "orange":
                        grid[y][x] = (pal["patch1"], "pattern")
                    elif patch == "dark":
                        grid[y][x] = (pal["patch2"], "pattern")
                    else:
                        grid[y][x] = (pal["base"], "base")

            elif variant == "cat-tuxedo":
                is_muzzle = frame_name in front_frames and y in range(13, 17) and x in range(13, 20)
                is_bib = frame_name in front_frames and y in range(18, 27) and x in range(14, 19)
                is_paw = y >= 25 and not (frame_name in ("sleep1", "sleep2") and y < 27)
                if is_muzzle or is_bib or is_paw:
                    grid[y][x] = (pal["light"], "light")
                else:
                    grid[y][x] = (pal["base"], "base")

    return grid


def build_xbm_golden_dog(vendor_dir, frame_name):
    """Colorize oneko's dog XBM into a bright golden retriever with a red collar."""
    dog_img = read_xbm(vendor_dir / "bitmaps" / "dog" / f"{frame_name}_dog.xbm")
    mask = read_xbm(vendor_dir / "bitmasks" / "dog" / f"{frame_name}_dog_mask.xbm")

    outline = (86, 48, 20, 255)
    gold = (244, 192, 78, 255)
    amber = (212, 142, 46, 255)
    cream = (254, 232, 176, 255)
    collar = (226, 66, 66, 255)
    eye = (44, 26, 16, 255)
    pink = (246, 134, 154, 255)
    zzz = (122, 198, 255, 255)

    front_frames = {"mati2", "jare2", "mati3", "awake", "down1", "down2"}
    grid = empty_grid()

    for y in range(SIZE):
        for x in range(SIZE):
            if not mask[y][x]:
                continue
            ink = bool(dog_img[y][x])

            if _zzz_region(frame_name, x, y):
                if ink:
                    grid[y][x] = (zzz, "zzz")
                continue

            if ink:
                if frame_name in front_frames and y in (11, 12, 13) and x in (13, 19):
                    grid[y][x] = (eye, "eye")
                elif frame_name in front_frames and y in (14, 15) and x in (15, 16, 17):
                    grid[y][x] = (outline, "detail")
                elif is_border_ink(mask, dog_img, x, y):
                    grid[y][x] = (outline, "outline")
                else:
                    # Keep interior dog fur warm amber instead of heavy dark ink blobs
                    if y in range(6, 17) and (x <= 10 or x >= 22):
                        grid[y][x] = (amber, "pattern")
                    elif frame_name in ("right1", "right2", "left1", "left2", "upleft1", "upleft2", "upright1", "upright2", "dwleft1", "dwleft2", "dwright1", "dwright2"):
                        # Keep eyes dark, soften chest/ear shading to amber
                        if y in (10, 11, 12, 13) and x in range(6, 26):
                            grid[y][x] = (amber, "pattern")
                        else:
                            grid[y][x] = (amber, "pattern")
                    else:
                        grid[y][x] = (amber, "pattern")
                continue

            if frame_name in ("mati2", "jare2", "mati3", "awake") and y == 17 and x in range(13, 20):
                grid[y][x] = (collar, "detail")
            elif frame_name == "mati3" and y in (15, 16) and x in (15, 16, 17):
                grid[y][x] = (pink, "detail")
            elif frame_name in front_frames and y in range(13, 17) and x in range(13, 20):
                grid[y][x] = (cream, "light")
            elif y >= 25:
                grid[y][x] = (cream, "light")
            elif y in range(6, 17) and (x <= 10 or x >= 22):
                grid[y][x] = (amber, "pattern")
            else:
                grid[y][x] = (gold, "base")

    return grid


