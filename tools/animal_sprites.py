def build_character_frames(vendor_dir, character_id, frame_names):
    """Return list of 32x32 tagged-RGBA grids for `character_id` in `frame_names` order."""
    if character_id in ("cat-ginger", "cat-calico", "cat-tuxedo"):
        return [build_xbm_cat(vendor_dir, name, character_id) for name in frame_names]
    if character_id == "dog-golden":
        return [build_xbm_golden_dog(vendor_dir, name) for name in frame_names]

    spec = CUSTOM_PALETTES[character_id]
    templates = _TEMPLATE_BUILDERS[spec["template"]]()
    pal = spec["palette"]

    frames = []
    for name in frame_names:
        raw = templates[name]
        if isinstance(raw, tuple) and raw[0] == "FLIP":
            frames.append(flip_grid(parse_art(raw[1], pal)))
        else:
            frames.append(parse_art(raw, pal))
    return frames


def downsample_16(grid):
    """Reduce a 32x32 tagged-RGBA grid to 16x16 while keeping fur bright and details sharp."""
    out = [[((0, 0, 0, 0), "empty") for _ in range(16)] for _ in range(16)]
    for y in range(16):
        for x in range(16):
            block = [
                grid[y * 2 + dy][x * 2 + dx]
                for dy in (0, 1)
                for dx in (0, 1)
            ]
            opaque = [(rgba, role) for rgba, role in block if rgba[3] > 0]
            if not opaque:
                continue

            # Preserve eyes and small details (nose, collar, bamboo, Zzz) first.
            special = [item for item in opaque if item[1] in ("eye", "detail", "zzz")]
            if special:
                out[y][x] = special[0]
                continue

            # Prefer interior fur/pattern over 1px outline unless the block is
            # mostly outline or an outer boundary with only outline pixels.
            interior = [item for item in opaque if item[1] != "outline"]
            outline_items = [item for item in opaque if item[1] == "outline"]
            if interior:
                if len(outline_items) >= 3 or (len(outline_items) >= 2 and len(interior) == 1):
                    out[y][x] = outline_items[0]
                else:
                    counts = {}
                    for rgba, role in interior:
                        counts[(role, rgba)] = counts.get((role, rgba), 0) + 1
                    out[y][x] = max(
                        interior,
                        key=lambda item: (counts[(item[1], item[0])], ROLE_PRIORITY[item[1]]),
                    )
            else:
                out[y][x] = outline_items[0]
    return out
